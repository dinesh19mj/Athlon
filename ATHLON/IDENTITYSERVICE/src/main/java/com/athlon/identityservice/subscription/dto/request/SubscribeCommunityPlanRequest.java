package com.athlon.identityservice.subscription.dto.request;

public class SubscribeCommunityPlanRequest {

    private Long organizationId;
    private String organizationUuid;

    private String planCode = "COMMUNITY_FREE"; // COMMUNITY_FREE or COMMUNITY_PRO
    private String billingCycle = "MONTHLY"; // MONTHLY, YEARLY
    private String paymentReference;

    public SubscribeCommunityPlanRequest() {
    }

    public Long getOrganizationId() {
        return organizationId;
    }

    public void setOrganizationId(Long organizationId) {
        this.organizationId = organizationId;
    }

    public String getOrganizationUuid() {
        return organizationUuid;
    }

    public void setOrganizationUuid(String organizationUuid) {
        this.organizationUuid = organizationUuid;
    }

    public String getPlanCode() {
        return planCode;
    }

    public void setPlanCode(String planCode) {
        this.planCode = planCode;
    }

    public String getBillingCycle() {
        return billingCycle;
    }

    public void setBillingCycle(String billingCycle) {
        this.billingCycle = billingCycle;
    }

    public String getPaymentReference() {
        return paymentReference;
    }

    public void setPaymentReference(String paymentReference) {
        this.paymentReference = paymentReference;
    }
}

